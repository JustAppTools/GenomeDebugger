test('phone layout, keyboard entry, and explicit identifier selection keep the task clear',async({page})=>{
  await page.setViewportSize({width:375,height:844})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Choose a starting point',exact:true})).toBeVisible()
  await page.keyboard.press('Tab')
  const focusState=await page.evaluate(()=>({tag:document.activeElement?.tagName,html:document.activeElement?.outerHTML.slice(0,250),hasFocus:document.hasFocus()}))
  await expect(page.getByRole('link',{name:'Skip to main content'}),JSON.stringify(focusState)).toBeFocused()
  await page.getByRole('button',{name:'Explore public data'}).click()
  await expect(page.getByRole('heading',{name:'Ensembl VEP · current GRCh38'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Reconstruct a comparison from saved VEP output'})).not.toBeVisible()
  await page.route('**/api/sources/resolve-identifier',route=>route.fulfill({json:{identifier:'rs123',choices:[{chromosome:'1',position:100,ref:'C',alt:'A'},{chromosome:'1',position:100,ref:'C',alt:'T'}],unsupported_records:0,notice:'Choose a mapping explicitly.',resolved_at:'2026-10-25T00:00:00Z',response:[],response_sha256:'a'.repeat(64)}}))
  let lookups=0;page.on('request',r=>{if(r.url().endsWith('/api/sources/ensembl/lookup'))lookups++})
  await page.getByText('Have an rsID or a simple HGVS substitution?',{exact:true}).click()
  await page.getByLabel('Public variant identifier').fill('rs123')
  await page.getByRole('button',{name:'Resolve with Ensembl'}).click()
  await expect(page.getByLabel('Position',{exact:true})).toHaveValue('6524705')
  await page.getByRole('button',{name:'Use GRCh38 1:100 C→T',exact:true}).click()
  await expect(page.getByLabel('Position',{exact:true})).toHaveValue('100')
  expect(lookups).toBe(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})

test('the readable report is portable HTML and escapes supplied markup',async({page,request},testInfo)=>{
  const input=await(await request.get('/api/demos/transcript-switch')).json()
  input.title='<img src=x onerror=alert(1)> Report'
  const result=await(await request.post('/api/investigations',{data:input})).json()
  await page.goto(`/#/comparison/${result.id}/overview`)
  await page.getByRole('button',{name:'Preview readable report'}).click()
  await expect(page.frameLocator('iframe[title="Comparison report preview"]').getByRole('heading',{name:input.title,exact:true})).toBeVisible()
  const downloaded=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download readable HTML'}).click()
  const download=await downloaded
  const output=testInfo.outputPath('readable-report.html');await download.saveAs(output)
  const {readFile}=await import('node:fs/promises');const text=await readFile(output,'utf8')
  expect(text).toContain('&lt;img src=x onerror=alert(1)&gt;')
  expect(text).not.toContain('<img src=x')
  expect(text).toContain('What the evidence supports')
})
