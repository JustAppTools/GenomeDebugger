test('explicit browser drafts resume after reload and edits can be undone',async({page,request})=>{
  const input=await(await request.get('/api/demos/transcript-switch')).json()
  input.title='Explicit local draft'
  await page.goto('/#/input')
  await page.getByRole('button',{name:'JSON editor',exact:true}).click()
  await page.getByLabel('Investigation JSON').fill(JSON.stringify(input))
  await page.getByRole('button',{name:'Save draft locally'}).click()
  await page.getByLabel('Investigation JSON').fill('{')
  await page.getByRole('button',{name:'Undo edit'}).click()
  await expect(page.getByLabel('Investigation JSON')).toHaveValue(JSON.stringify(input))
  await page.reload()
  await page.getByRole('button',{name:'Resume saved draft'}).click()
  await expect(page.getByLabel('Investigation title')).toHaveValue('Explicit local draft')
  await page.getByRole('button',{name:'Discard saved draft'}).click()
  await page.reload()
  await expect(page.getByRole('button',{name:'Resume saved draft'})).toHaveCount(0)
})

test('names and archive restoration leave scientific input unchanged',async({page,request})=>{
  const input=await(await request.get('/api/demos/transcript-switch')).json()
  input.title=`Library organization ${Date.now()} ${Math.random()}`
  const saved=await(await request.post('/api/investigations',{data:input})).json()
  await page.goto('/#/library')
  await page.getByLabel('Search investigations').fill(input.title)
  const row=page.locator('.library-row').filter({hasText:input.title})
  await row.getByRole('button',{name:'Edit details'}).click()
  await page.getByLabel('Display name').fill('Recognizable saved comparison')
  await page.getByLabel('Notes',{exact:true}).fill('Review with the producing analyst')
  await page.getByLabel('Tags (comma separated)').fill('release, review')
  await page.getByRole('button',{name:'Save library details'}).click()
  const renamed=page.locator('.library-row').filter({hasText:saved.id})
  await expect(renamed).toBeVisible()
  await renamed.getByRole('button',{name:'Archive',exact:true}).click()
  await expect(renamed).toHaveCount(0)
  await page.getByLabel('Show',{exact:true}).selectOption('archived')
  await renamed.getByRole('button',{name:'Restore',exact:true}).click()
  await page.getByLabel('Show',{exact:true}).selectOption('active')
  await renamed.getByRole('button',{name:'Open',exact:true}).click()
  await expect(page).toHaveURL(new RegExp(`/comparison/${saved.id}/overview`))
  const unchanged=await(await request.get(`/api/investigations/${saved.id}`)).json()
  expect(unchanged.input_sha256).toBe(saved.input_sha256)
  expect(unchanged.input).toEqual(saved.input)
  await page.goBack()
  await expect(page.getByRole('heading',{name:'Your saved comparisons'})).toBeVisible()
})

